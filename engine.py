
import csv
import os
from datetime import datetime

try:
    import joblib
except ModuleNotFoundError:
    joblib = None


class AgriEngine:

    def __init__(self, data_folder):
        self.data_folder = data_folder
        self.model_path = os.path.join(
            data_folder, "crop_model.pkl"
        )
        self.model = None

        if os.path.exists(self.model_path) and joblib is not None:
            self.model = joblib.load(self.model_path)

    def analyze_soil(self, values):
        moisture = float(values["moisture"])
        temperature = float(values["temperature"])
        humidity = float(values["humidity"])
        nitrogen = float(values["N"])
        phosphorus = float(values["P"])
        potassium = float(values["K"])
        ph = float(values["ph"])

        warnings = []

        if moisture < 25:
            warnings.append("Soil moisture is low.")
        elif moisture > 80:
            warnings.append("Soil moisture is high.")

        if temperature > 35:
            warnings.append("High temperature detected.")

        if ph < 5.5:
            warnings.append("Soil is acidic.")
        elif ph > 7.5:
            warnings.append("Soil is alkaline.")

        if nitrogen < 40:
            warnings.append("Nitrogen level may be low.")

        if phosphorus < 20:
            warnings.append("Phosphorus level may be low.")

        if potassium < 20:
            warnings.append("Potassium level may be low.")

        if not warnings:
            warnings.append(
                "No major warning from the entered values."
            )

        return {
            "moisture": moisture,
            "temperature": temperature,
            "humidity": humidity,
            "N": nitrogen,
            "P": phosphorus,
            "K": potassium,
            "ph": ph,
            "warnings": warnings
        }

    def predict_crop(self, values):
        if self.model is None:
            return {
                "crop": "Model not trained",
                "status": "unavailable",
                "message": (
                    "Add the crop recommendation dataset "
                    "and train the model first."
                )
            }

        features = [[
            float(values["N"]),
            float(values["P"]),
            float(values["K"]),
            float(values["temperature"]),
            float(values["humidity"]),
            float(values["ph"]),
            float(values["rainfall"])
        ]]

        prediction = self.model.predict(features)[0]

        return {
            "crop": str(prediction),
            "status": "success",
            "message": "Prediction generated by the trained model."
        }

    def analyze_telemetry(self, csv_path):
        if not os.path.exists(csv_path):
            raise FileNotFoundError("Telemetry CSV file not found.")

        with open(csv_path, newline="", encoding="utf-8") as file:
            reader = csv.DictReader(line for line in file if line.strip())
            if not reader.fieldnames or not {
                "timestamp", "soil_moisture"
            }.issubset(reader.fieldnames):
                raise ValueError(
                    "Telemetry CSV must contain timestamp and soil_moisture columns."
                )

            records = []
            for row in reader:
                try:
                    timestamp = datetime.fromisoformat(row["timestamp"])
                    moisture = float(row["soil_moisture"])
                except (TypeError, ValueError):
                    continue
                records.append((timestamp, moisture))

        records.sort(key=lambda record: record[0])
        recent = records[-7:]

        if not recent:
            raise ValueError("No valid telemetry records found.")

        first_value = recent[0][1]
        last_value = recent[-1][1]

        difference = round(last_value - first_value, 2)

        if difference < -5:
            trend = "Decreasing"
        elif difference > 5:
            trend = "Increasing"
        else:
            trend = "Stable"

        return {
            "records": len(recent),
            "first_moisture": first_value,
            "latest_moisture": last_value,
            "change": difference,
            "trend": trend,
            "dates": [
                timestamp.strftime("%Y-%m-%d")
                for timestamp, _ in recent
            ],
            "moisture_values": [moisture for _, moisture in recent]
        }

    def run_agent(self, values, telemetry=None):
        steps = []

        soil = self.analyze_soil(values)
        steps.append({
            "tool": "Soil Analysis",
            "status": "completed",
            "result": "Soil parameters analyzed."
        })

        crop = self.predict_crop(values)
        steps.append({
            "tool": "Crop Recommendation",
            "status": crop["status"],
            "result": crop["crop"]
        })

        if telemetry:
            steps.append({
                "tool": "Telemetry Analysis",
                "status": "completed",
                "result": telemetry["trend"]
            })
        else:
            steps.append({
                "tool": "Telemetry Analysis",
                "status": "unavailable",
                "result": "No valid telemetry readings are available."
            })

        steps.append({
            "tool": "Weather Check",
            "status": "not_connected",
            "result": (
                "Live weather service is not connected. "
                "Rainfall input is used only as provided."
            )
        })

        advice = []

        if soil["moisture"] < 25:
            advice.append(
                "Soil moisture is low. Check the crop's "
                "water requirement and field condition."
            )
        elif soil["moisture"] > 80:
            advice.append(
                "Soil moisture is high. Check drainage and monitor the field for standing water."
            )

        if soil["temperature"] > 35:
            advice.append(
                "High temperature detected. Monitor the crop "
                "during the hottest hours."
            )

        nutrient_thresholds = {"N": 40, "P": 20, "K": 20}
        for nutrient, name in (
            ("N", "Nitrogen"),
            ("P", "Phosphorus"),
            ("K", "Potassium")
        ):
            if soil[nutrient] < nutrient_thresholds[nutrient]:
                advice.append(
                    f"{name} may be low. Confirm with a soil test before changing fertilizer use."
                )

        if soil["ph"] < 5.5 or soil["ph"] > 7.5:
            advice.append(
                "Consider a soil test before making pH corrections."
            )

        if not advice:
            advice.append(
                "Continue monitoring soil conditions regularly."
            )

        return {
            "soil": soil,
            "crop": crop,
            "telemetry": telemetry,
            "steps": steps,
            "advice": advice,
            "created_at": datetime.now().isoformat()
        }
